const seen = new Map()
const contents = new Map()
let changed = 0

for (const [name, targetIndex, rows] of jobs) {
  const file = path.join(DIR, name)
  const content = contents.get(name) || fs.readFileSync(file, 'utf8')
  const signature = markdownRows(rows.slice(0, 1))
  if (content.includes(signature)) {
    console.log(`SKIP ${name}: table already restored`)
    continue
  }
  const tablePattern = /(^\|.*\|\n^\|(?:\s*:?-+:?\s*\|)+\n)(?!\|)/gm
  let occurrence = -1
  let updated = content.replace(tablePattern, (match) => {
    occurrence += 1
    if (occurrence !== targetIndex) return match
    return `${match}${markdownRows(rows)}\n`
  })
  if (updated === content) {
    console.error(`FAIL ${name}: empty table ${targetIndex + 1} not found`)
    process.exitCode = 1
    continue
  }
  contents.set(name, updated)
  changed += 1
  seen.set(name, (seen.get(name) || 0) + 1)
  console.log(`${WRITE ? 'WRITE' : 'DRY'} ${name}: ${rows.length} rows`)
}

if (WRITE && !process.exitCode) {
  for (const [name, content] of contents) {
    fs.writeFileSync(path.join(DIR, name), content)
  }
}

console.log(`${WRITE ? 'Restored' : 'Would restore'} ${changed} partnership tables in ${seen.size} files.`)
