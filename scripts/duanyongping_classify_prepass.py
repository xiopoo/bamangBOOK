def extract_text(inv_row):
    """提取标题 + 正文首段（含提问行），用于关键词匹配"""
    parts = [inv_row.get("title", "")]
    try:
        with open(inv_row["file_path"], encoding="utf-8") as f:
            text = f.read()
        # 剥离 frontmatter
        if text.startswith("---"):
            m = re.match(r"^---\r?\n.*?\r?\n---\r?\n", text, re.S)
            if m:
                text = text[m.end():]
        # 取前 400 字（含提问）
        parts.append(text[:400])
    except Exception:
        parts.append(inv_row.get("body_first_line", ""))
    return "\n".join(parts).lower()


def classify(text):
    # 先公司强信号
    for ch, kws in COMPANY_PRIORITY:
        for kw in kws:
            if kw in text:
                return ch, f"公司关键词:{kw}"
    # 再泛规则
    for ch, kws, desc in RULES:
        for kw in kws:
            if kw in text:
                return ch, f"{desc}关键词:{kw}"
    return "", "未命中，待人工判定"


def main():
    rows = []
    with open(INV_CSV, encoding="utf-8") as f:
        for r in csv.DictReader(f):
            if r["source_type"] in ("blog", "qa", "talks", "milestones", "speeches"):
                rows.append(r)
    out = []
    for r in rows:
        text = extract_text(r)
        ch, why = classify(text)
        out.append({
            "unit_id": r["unit_id"],
            "source_type": r["source_type"],
            "title": r["title"],
            "candidate_chapter": ch,
            "reason": why,
        })
    os.makedirs(MANIFEST_DIR, exist_ok=True)
    with open(OUT_CSV, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["unit_id", "source_type", "title", "candidate_chapter", "reason"])
        w.writeheader()
        for o in out:
            w.writerow(o)
    from collections import Counter
    c = Counter(o["candidate_chapter"] for o in out)
    print(f"预分类单元: {len(out)}")
    for k, v in sorted(c.items(), key=lambda x: -x[1]):
        print(f"  {k or '(空)'}: {v}")
    print(f"输出: {OUT_CSV}")


if __name__ == "__main__":
    main()
