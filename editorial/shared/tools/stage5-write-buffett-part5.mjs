子公司经理人拥有经营自主权，总部集中CEO选择、重大资本配置、流动性和声誉边界。这种不对称让专业知识留在业务现场，又让现金跨企业比较。

结构依赖信任、审计和信息上报。没有共同品行边界，分权会碎裂；没有自主权，集团会官僚化；没有集中配置，多余现金会被局部增长目标困住。

