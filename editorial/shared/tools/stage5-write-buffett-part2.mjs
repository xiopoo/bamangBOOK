GEICO提供不同类型的证据。汽车保险是许多家庭的大额支出，客户重视节省；低成本运营使公司能够以有吸引力的价格承保，同时保留合理利润。巴菲特早在1951年研究GEICO时就注意到直接销售带来的成本优势，后来的股东信把它明确称为持久护城河。

