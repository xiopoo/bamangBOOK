function source(file) {
  return fs.readFileSync(path.join(root, file), "utf8").replace(/^# .+\n+/u, "").trim();
}

function between(file, start, end) {
  const text = fs.readFileSync(path.join(root, file), "utf8");
  const from = text.indexOf(start);
  const to = text.indexOf(end, from);
  if (from < 0 || to < 0) throw new Error(`Cannot select ${file}: ${start} -> ${end}`);
  return text.slice(from, to + end.length).trim();
}

function quote(text) {
  return text.split("\n").map((line) => line ? `> ${line}` : ">").join("\n");
}

function paragraphContaining(file, phrase) {
  const paragraph = fs.readFileSync(path.join(root, file), "utf8")
    .split(/\n\s*\n/u)
    .find((item) => item.includes(phrase));
  if (!paragraph) throw new Error(`Cannot find paragraph ${phrase} in ${file}`);
  return paragraph.trim();
}

function paragraphsContaining(file, phrases) {
  return phrases.map((phrase) => paragraphContaining(file, phrase)).join("\n\n");
}

